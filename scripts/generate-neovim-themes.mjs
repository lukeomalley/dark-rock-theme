function toLua(value, indentLevel = 0) {
  if (typeof value === "string") {
    return JSON.stringify(value);
  }

  if (typeof value === "number" || typeof value === "boolean") {
    return String(value);
  }

  if (Array.isArray(value)) {
    return `{ ${value.map((item) => toLua(item, indentLevel)).join(", ")} }`;
  }

  if (value && typeof value === "object") {
    return toLuaTable(value, indentLevel);
  }

  return "nil";
}

function toLuaTable(object, indentLevel = 0) {
  const entries = Object.entries(object);

  if (entries.length === 0) {
    return "{}";
  }

  const indentation = "  ".repeat(indentLevel);
  const childIndentation = "  ".repeat(indentLevel + 1);
  const lines = entries.map(([key, value]) => `${childIndentation}${getLuaKey(key)} = ${toLua(value, indentLevel + 1)},`);

  return `{\n${lines.join("\n")}\n${indentation}}`;
}

function getLuaKey(key) {
  if (/^[a-zA-Z_][a-zA-Z0-9_]*$/.test(key)) {
    return key;
  }

  return `[${JSON.stringify(key)}]`;
}

