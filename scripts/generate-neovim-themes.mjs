function getColor(theme, keys, fallback, alphaBase) {
  const color = keys.map((key) => theme.colors?.[key]).find(Boolean);
  return normalizeHex(color ?? fallback, alphaBase);
}

function getTokenStyle(theme, preferredScopes, fallback) {
  const preferredScopeSet = new Set(preferredScopes);
  const token = theme.tokenColors?.find((tokenColor) =>
    getScopes(tokenColor.scope).some((scope) => preferredScopeSet.has(scope)),
  );

  if (!token?.settings) {
    return fallback;
  }

  return settingsToHighlight(token.settings, fallback);
}

function getScopes(scope) {
  if (Array.isArray(scope)) {
    return scope.flatMap(getScopes);
  }

  if (typeof scope !== "string") {
    return [];
  }

  return scope
    .split(",")
    .map((part) => part.trim())
    .filter(Boolean);
}

function settingsToHighlight(settings, fallback) {
  const highlight = { ...fallback };

  if (settings.foreground) {
    highlight.fg = normalizeHex(settings.foreground);
  }

  if (settings.background) {
    highlight.bg = normalizeHex(settings.background);
  }

  for (const style of getFontStyles(settings.fontStyle)) {
    highlight[style] = true;
  }

  return highlight;
}

function getFontStyles(fontStyle) {
  if (!fontStyle) {
    return [];
  }

  return fontStyle
    .split(/\s+/)
    .map((style) => style.trim())
    .filter((style) => ["bold", "italic", "underline", "strikethrough"].includes(style));
}

function normalizeHex(color, alphaBase) {
  if (typeof color !== "string") {
    return color;
  }

  const normalizedColor = color.toLowerCase();

  if (/^#[0-9a-f]{8}$/i.test(normalizedColor)) {
    if (alphaBase) {
      return blendHex(normalizedColor, alphaBase);
    }

    return normalizedColor.slice(0, 7);
  }

  return normalizedColor;
}

function blendHex(color, alphaBase) {
  const foreground = hexToRgb(color.slice(0, 7));
  const background = hexToRgb(alphaBase);

  if (!foreground || !background) {
    return color.slice(0, 7);
  }

  const alpha = Number.parseInt(color.slice(7, 9), 16) / 255;
  const blended = {
    r: Math.round(foreground.r * alpha + background.r * (1 - alpha)),
    g: Math.round(foreground.g * alpha + background.g * (1 - alpha)),
    b: Math.round(foreground.b * alpha + background.b * (1 - alpha)),
  };

  return rgbToHex(blended);
}

function hexToRgb(color) {
  const match = color.match(/^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i);

  if (!match) {
    return null;
  }

  return {
    r: Number.parseInt(match[1], 16),
    g: Number.parseInt(match[2], 16),
    b: Number.parseInt(match[3], 16),
  };
}

function rgbToHex({ r, g, b }) {
  return `#${[r, g, b].map((value) => value.toString(16).padStart(2, "0")).join("")}`;
}

async function writePalette(palette) {
  const targetPath = path.join(PALETTE_DIR, `${palette.slug}.lua`);
  await writeFile(targetPath, GENERATED_HEADER + `return ${toLua(palette)}\n`);
}

async function writeColorscheme(themeConfig) {
  const targetPath = path.join(COLORSCHEME_DIR, `${themeConfig.slug}.lua`);
  const content = `${GENERATED_HEADER}require("dark-rock").setup("${themeConfig.slug}")\n`;
  await writeFile(targetPath, content);
}

function getInitModule() {
  return `${GENERATED_HEADER}local M = {}

local default_options = {
  transparent = vim.g.dark_rock_transparent == true or vim.g.dark_rock_transparent == 1,
  nvim_tree_folder_color = vim.g.dark_rock_nvim_tree_folder_color or "fgAlt",
}

M.options = vim.deepcopy(default_options)

local function apply_highlights(groups)
  for group, spec in pairs(groups) do
    vim.api.nvim_set_hl(0, group, spec)
  end
end

local function normalize_setup_args(theme_name, options)
  if type(theme_name) == "table" then
    return theme_name.theme or theme_name.name or "dark-rock", theme_name
  end

  return theme_name or "dark-rock", options or {}
end

function M.configure(options)
  M.options = vim.tbl_deep_extend("force", M.options, options or {})
end

function M.setup(theme_name, options)
  local selected_theme_name, setup_options = normalize_setup_args(theme_name, options)
  local ok, palette = pcall(require, "dark-rock.palettes." .. selected_theme_name)

  if not ok then
    error(("dark-rock theme %q not found"):format(selected_theme_name))
  end

  M.configure(setup_options)

  vim.o.termguicolors = true
  vim.o.background = palette.background

  vim.cmd("highlight clear")

  if vim.fn.exists("syntax_on") == 1 then
    vim.cmd("syntax reset")
  end

  vim.g.colors_name = selected_theme_name

  apply_highlights(require("dark-rock.highlights").get(palette, M.options))
end

return M
`;
}

