const PALETTE_DIR = path.join(REPO_ROOT, "nvim", "lua", "dark-rock", "palettes");
const LUA_MODULE_DIR = path.join(REPO_ROOT, "nvim", "lua", "dark-rock");
const COLORSCHEME_DIR = path.join(REPO_ROOT, "nvim", "colors");

async function main() {
  await mkdir(PALETTE_DIR, { recursive: true });
  await mkdir(COLORSCHEME_DIR, { recursive: true });

  const palettes = await Promise.all(THEMES.map(readPalette));

  await Promise.all(palettes.map(writePalette));
  await writeFile(path.join(LUA_MODULE_DIR, "highlights.lua"), getHighlightsModule());
  await writeFile(path.join(LUA_MODULE_DIR, "init.lua"), getInitModule());
  await Promise.all(THEMES.map(writeColorscheme));

  console.log(`Generated ${THEMES.length} Neovim themes in nvim/`);
}

async function readPalette(themeConfig) {
  const themePath = path.join(REPO_ROOT, themeConfig.sourcePath);
  const theme = parseJsonc(await readFile(themePath, "utf8"));

  return {
    name: theme.name ?? themeConfig.name,
    slug: themeConfig.slug,
    background: theme.type === "light" ? "light" : "dark",
    colors: getUiColors(theme),
    syntax: getSyntaxColors(theme),
  };
}

function parseJsonc(contents) {
  return JSON.parse(contents.replace(/^\s*\/\/.*$/gm, ""));
}

